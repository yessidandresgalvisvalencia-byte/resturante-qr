"use strict";
const assert=require("node:assert/strict"),mongoose=require("mongoose");
const Tx=require("../../../modules/finanzas-personales/models/TransaccionPersonal");
const Accion=require("../../../modules/finanzas-personales/models/accionProgresoPersonal.model");
const {registrarTransaccion}=require("../../../modules/finanzas-personales/services/flujoCajaPersonal.service");
const aplicar=require("../../../modules/finanzas-personales/services/compensarMovimientoPersonal.service").crearAplicador();
const {analizar}=require("../../../modules/finanzas-personales/services/progresoEconomicoPersonal.service");
async function probarProgresoEconomicoAutorizado(){
 const usuarioId=new mongoose.Types.ObjectId();
 const datos={cuenta:"EFECTIVO",fecha:new Date(Date.now()-60000),concepto:"Progreso de prueba",categoria:"Gasto hormiga"};
 await registrarTransaccion(usuarioId,{...datos,tipo:"INGRESO",montoMinor:10000,externalId:"progreso-ingreso"});
 const gasto=await registrarTransaccion(usuarioId,{...datos,tipo:"GASTO",montoMinor:2000,externalId:"progreso-gasto"});
 const fuentes=await Tx.find({usuarioId}).sort({_id:1}).lean();
 const corregir=(montoMinor,idempotencyKey)=>aplicar({usuarioId,movimientoId:String(gasto._id),tipo:"CORRECCION",cambios:{montoMinor},idempotencyKey});
 const primero=await analizar(usuarioId);
 assert.equal(primero.metricas.ingresosMinor,10000);assert.equal(primero.metricas.gastosMinor,2000);
 const propuesta=primero.acciones.find(a=>a.palanca==="GASTO");assert.ok(propuesta);
 await corregir(1800,"progreso-1800");
 const actualizado=await analizar(usuarioId),pendiente=actualizado.acciones.find(a=>a.palanca==="GASTO");
 assert.equal(String(pendiente._id),String(propuesta._id));assert.equal(pendiente.objetivoMinor,1800);assert.equal(pendiente.baselineMinor,1800);
 await corregir(1000,"progreso-1000");
 const menor=await analizar(usuarioId);assert.equal(menor.metricas.gastosMinor,1000);
 assert.ok(!menor.acciones.some(a=>a.palanca==="GASTO"));
 assert.ok(!menor.ordenes.some(a=>a.palanca==="GASTO"));
 await corregir(1900,"progreso-1900");await analizar(usuarioId);
 await Accion.updateOne({_id:propuesta._id,usuarioId},{$set:{estado:"APROBADA"}});
 await corregir(1700,"progreso-1700");
 const aprobado=await analizar(usuarioId),compromiso=aprobado.acciones.find(a=>String(a._id)===String(propuesta._id));
 assert.equal(aprobado.metricas.gastosMinor,1700);assert.equal(compromiso.baselineMinor,1900);assert.equal(compromiso.estado,"APROBADA");
 await aplicar({usuarioId,movimientoId:String(gasto._id),tipo:"ANULACION",idempotencyKey:"progreso-anular"});
 const anulado=await analizar(usuarioId);
 assert.equal(anulado.metricas.gastosMinor,0);assert.equal(anulado.metricas.gastoHormigaMinor,0);
 assert.deepEqual(await Tx.find({usuarioId}).sort({_id:1}).lean(),fuentes);
 const otro=new mongoose.Types.ObjectId();
 await registrarTransaccion(otro,{...datos,tipo:"INGRESO",montoMinor:123456,externalId:"progreso-otro"});
 assert.equal((await analizar(usuarioId)).metricas.ingresosMinor,10000);
 assert.equal(await Accion.countDocuments({usuarioId:otro}),0);
}
module.exports={probarProgresoEconomicoAutorizado};
