'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const os=require('node:os');
const path=require('node:path');
const {generateKeyPairSync,createHash}=require('node:crypto');
const {createKeyring}=require('../../scripts/gruk/drive-manifest-keyring');
const {createKeyringReceipt}=require('../../scripts/gruk/drive-signed-receipt');
const {runCatalog}=require('../../scripts/gruk/drive-catalog-runtime');
test('catalog runtime persists verified receipt through independent adapter and fails closed',async t=>{
 const dir=await fs.mkdtemp(path.join(os.tmpdir(),'gruk-catalog-runtime-'));
 t.after(()=>fs.rm(dir,{recursive:true,force:true}));
 const file=path.join(dir,'backup.age'),receiptPath=path.join(dir,'receipt.json'),name='gruk-restaurante-1-1.archive.age';
 await fs.writeFile(file,Buffer.alloc(100,1));
 const {publicKey,privateKey}=generateKeyPairSync('ed25519');
 const keyId=createHash('sha256').update(publicKey.export({type:'spki',format:'der'})).digest('hex');
 const config={activeKeyId:keyId,keys:[{keyId,status:'active',publicKey:publicKey.export({type:'spki',format:'pem'})}]};
 await createKeyringReceipt(file,name,receiptPath,createKeyring(config),privateKey);
 const env={GRUK_CATALOG_ENABLED:'true',GRUK_MANIFEST_TRUSTED_KEYRING:JSON.stringify(config),GRUK_CATALOG_MONGO_URI:'mongodb+srv://catalog:fake@catalog.example.mongodb.net/gruk_storage_catalog',GRUK_ENTERPRISE_BACKUP_URI:'mongodb+srv://source:fake@source.example.mongodb.net/restaurante',GRUK_CATALOG_EXPECTED_HOST:'catalog.example.mongodb.net'};
 const rows=new Map();let calls=0,closed=0;
 const connect=async()=>{calls++;return {db:{databaseName:'gruk_storage_catalog',collection(){return {async insertOne(row){rows.set(row._id,row);return {acknowledged:true,insertedId:row._id};},async findOne(q){return rows.get(q._id)||null;}};}},async close(){closed++;}};};
 const args={file,name,receiptPath,env,connect};
 await assert.rejects(runCatalog({...args,mode:'register',env:{...env,GRUK_CATALOG_ENABLED:'false'}}),/CATALOG_RUNTIME_DISABLED/);
 assert.equal(calls,0);
 assert.equal((await runCatalog({...args,mode:'register'})).restoreVerified,false);
 assert.equal((await runCatalog({...args,mode:'verify'})).bytes,100);
 assert.equal(closed,2);
 await fs.writeFile(file,Buffer.alloc(100,2));
 await assert.rejects(runCatalog({...args,mode:'verify'}),/MANIFEST_INTEGRITY_MISMATCH/);
 assert.equal(calls,2);
});
