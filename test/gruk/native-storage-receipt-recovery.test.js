'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const os=require('node:os');
const path=require('node:path');
const {generateKeyPairSync}=require('node:crypto');
const {createManifest}=require('../../scripts/gruk/drive-backup-manifest');
const {signManifest,verifySignedManifest}=require('../../scripts/gruk/drive-manifest-signature');
const {createCatalog}=require('../../scripts/gruk/drive-backup-catalog');
const {persistReceipt,recoverReceipt}=require('../../scripts/gruk/native-storage-receipt-recovery');
test('recover only pre-signed intact archives, without signing key or overwrite',async t=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'gruk-receipt-'));t.after(()=>fs.rm(root,{recursive:true,force:true}));
 const name='gruk-restaurante-1-1.archive.age',file=path.join(root,name);
 await fs.writeFile(file,'age-encryption.org/v1\n'+'x'.repeat(100),{mode:0o600});
 const {privateKey,publicKey}=generateKeyPairSync('ed25519');
 const keyring={verify:(r,n)=>verifySignedManifest(r,publicKey,n)};
 const receipt=signManifest(await createManifest(file,name),privateKey);
 const data=new Map();
 const catalog=createCatalog({keyring,store:{async putIfAbsent(n,v){if(data.has(n))return false;data.set(n,v);return true;},async get(n){return data.get(n);}}});
 const args={root,name,keyring,catalog};
 await assert.rejects(recoverReceipt(args),{code:'ENOENT'});
 await persistReceipt({...args,receipt});
 await assert.rejects(persistReceipt({...args,receipt}),{code:'EEXIST'});
 assert.equal((await recoverReceipt(args)).status,'REGISTERED');
 await recoverReceipt(args);assert.equal(data.size,1);
 await fs.writeFile(file,'age-encryption.org/v1\n'+'y'.repeat(100));
 await assert.rejects(recoverReceipt(args),/RECOVERY_ARCHIVE_UNVERIFIED/);
});
