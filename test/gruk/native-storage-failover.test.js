'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const os=require('node:os');
const path=require('node:path');
const {generateKeyPairSync}=require('node:crypto');
const {createManifest}=require('../../scripts/gruk/drive-backup-manifest');
const {signManifest,verifySignedManifest}=require('../../scripts/gruk/drive-manifest-signature');
const {persistReceipt}=require('../../scripts/gruk/native-storage-receipt-recovery');
const {stageRecovery}=require('../../scripts/gruk/native-storage-failover');
test('failover stages verified replica, preserves damaged original and rejects overwrite',async t=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'gruk-failover-'));t.after(()=>fs.rm(root,{recursive:true,force:true}));
 const [primaryRoot,replicaRoot,recoveryRoot]=['primary','replica','recovery'].map(n=>path.join(root,n));
 for(const r of [primaryRoot,replicaRoot,recoveryRoot])await fs.mkdir(r,{mode:0o700});
 const name='gruk-restaurante-1-1.archive.age',bytes=Buffer.from('age-encryption.org/v1\n'+'x'.repeat(100));
 const {privateKey,publicKey}=generateKeyPairSync('ed25519');
 const keyring={verify:(r,n)=>verifySignedManifest(r,publicKey,n)};
 for(const r of [primaryRoot,replicaRoot])await fs.writeFile(path.join(r,name),bytes,{mode:0o600});
 const manifest=await createManifest(path.join(replicaRoot,name),name),receipt=signManifest(manifest,privateKey);
 for(const r of [primaryRoot,replicaRoot])await persistReceipt({root:r,name,keyring,receipt});
 await fs.writeFile(path.join(primaryRoot,name),'damaged');
 const args={primaryRoot,replicaRoot,recoveryRoot,name,keyring,catalog:{lookup:async()=>manifest}};
 assert.deepEqual(await stageRecovery(args),{status:'STAGED',source:'replica',receiptVerified:true,restoreVerified:false});
 assert.deepEqual(await fs.readFile(path.join(recoveryRoot,name)),bytes);
 assert.equal(await fs.readFile(path.join(primaryRoot,name),'utf8'),'damaged');
 await assert.rejects(stageRecovery(args),{code:'EEXIST'});
 await assert.rejects(stageRecovery({...args,recoveryRoot:primaryRoot}),/FAILOVER_ROOT_OVERLAP/);
 await fs.writeFile(path.join(replicaRoot,name),'damaged');
 await assert.rejects(stageRecovery(args),/FAILOVER_NO_VERIFIED_COPY/);
});
