'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
const os=require('node:os');
const path=require('node:path');
const {createHash}=require('node:crypto');
const {createNativeCatalogInspector}=require('../../scripts/gruk/native-storage-catalog-inspector');
const name='gruk-restaurante-1-1.archive.age';
test('native vault checks signed-catalog metadata, digest and private file constraints without network',async t=>{
 const root=await fs.mkdtemp(path.join(os.tmpdir(),'gruk-vault-'));
 t.after(()=>fs.rm(root,{recursive:true,force:true}));
 const file=path.join(root,name);
 const bytes=Buffer.from('age-encryption.org/v1\n'+'x'.repeat(100));
 const manifest={version:1,database:'restaurante',name,bytes:bytes.length,sha256:createHash('sha256').update(bytes).digest('hex')};
 const inspect=createNativeCatalogInspector({root,catalog:{lookup:async()=>manifest}});
 assert.equal((await inspect(name)).status,'ARCHIVE_MISSING');
 await fs.writeFile(file,bytes,{mode:0o600});
 assert.deepEqual(await inspect(name),{name,status:'RESTORE_VERIFICATION_REQUIRED',restoreVerified:false});
 await fs.writeFile(file,Buffer.from('age-encryption.org/v1\n'+'y'.repeat(100)));
 assert.equal((await inspect(name)).status,'ARCHIVE_DIGEST_MISMATCH');
 await fs.writeFile(file,bytes.subarray(0,64));
 assert.equal((await inspect(name)).status,'ARCHIVE_SIZE_MISMATCH');
 await fs.unlink(file);await fs.symlink('/etc/passwd',file);
 assert.equal((await inspect(name)).status,'VAULT_UNVERIFIED');
 await assert.rejects(inspect('../escape'),/NATIVE_INSPECTOR_NAME/);
 const missing=createNativeCatalogInspector({root,catalog:{lookup:async()=>{throw Error('CATALOG_NOT_FOUND')}}});
 assert.equal((await missing(name)).status,'CATALOG_MISSING');
});
