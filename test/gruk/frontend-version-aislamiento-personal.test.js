"use strict";
const test=require("node:test");
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
test("el HTML personal referencia la version de frontend de las correcciones de sesion",()=>{
 const html=fs.readFileSync(path.join(__dirname,"../../public/finanzas-personales.html"),"utf8");
 assert.match(html,/src="\/finanzas-personales\.js\?v=20261112-copia-diario-v81"/);
 assert.doesNotMatch(html,/finanzas-personales\.js\?v=20261015-integridad-v2/);
 const rutas=["finanzas-personales-imputacion.js","finanzas-personales-recuperacion.js","finanzas-personales-control-mutaciones.js","finanzas-personales.js"].map(n=>"/"+n+"?v="+(n==="finanzas-personales.js"?"20261112-copia-diario-v81":"20261106-cierre-calendario-v81"));
 assert.match(html,/src="\/finanzas-personales-constancia\.js\?v=20261112-copia-diario-v81"/);
 assert.ok(html.indexOf('/finanzas-personales-constancia.js?v=20261112-copia-diario-v81')<html.indexOf('/finanzas-personales-manual.js?v=20261112-copia-diario-v81'));
 assert.ok(html.indexOf('/finanzas-personales-manual.js?v=20261112-copia-diario-v81')<html.indexOf(rutas[3]),"diario manual carga antes de la aplicación");
 assert.equal(html.split('src="/finanzas-personales-diario-portable.js?v=20261112-copia-diario-v81"').length-1,1);
 assert.ok(html.indexOf('/finanzas-personales-diario-portable.js?v=20261112-copia-diario-v81')<html.indexOf('/finanzas-personales-manual.js?v=20261112-copia-diario-v81'));
 for(const ruta of rutas)assert.equal(html.split('src="'+ruta+'"').length-1,1);
 assert.ok(html.indexOf(rutas[0])<html.indexOf(rutas[1])&&html.indexOf(rutas[1])<html.indexOf(rutas[2])&&html.indexOf(rutas[2])<html.indexOf(rutas[3]),"control e imputación cargan antes de la aplicación");
 assert.match(html,/href="\/finanzas-personales\.css\?v=20261019-integridad-sesion-coldstart"/);
 assert.doesNotMatch(html,/finanzas-personales\.css\?v=20261013-bubble2/);
 assert.match(html,/<meta http-equiv="Cache-Control" content="no-store">/);
});
